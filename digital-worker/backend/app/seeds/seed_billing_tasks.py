def seed_billing_tasks():
    session = Session()
    r = random.Random(42)
    now = datetime.now()

    # Clear old data
    session.execute(text("SET FOREIGN_KEY_CHECKS = 0"))
    session.execute(text("TRUNCATE TABLE ma_task_monitor"))
    session.execute(text("SET FOREIGN_KEY_CHECKS = 1"))
    session.commit()
    print("Cleared ma_task_monitor")

    total = 0
    for cid, am, base in CYCLES:
        for code, name, wt, so, eo in TASKS:
            ps = base + timedelta(minutes=so)
            pe = base + timedelta(minutes=eo)
            if pe < now:
                s = r.choice(["已完成","已完成","已完成","已完成","已完成","已完成","异常"])
            elif ps < now:
                s = r.choice(["进行中","进行中","已完成","未开始"])
            else:
                s = r.choice(["未开始","未开始","未开始","未开始","未开始","进行中"])
            se = SMAP[s]
            ast = None; aet = None
            if se == "completed":
                ast = ps - timedelta(minutes=r.randint(0,10))
                aet = pe - timedelta(minutes=r.randint(-5,15))
            elif se == "running":
                ast = ps - timedelta(minutes=r.randint(0,5))
            pct = 100 if se == "completed" else (50 if se == "running" else 0)
            dur = (eo - so) * 60
            session.add(MaTaskMonitor(
                account_month=am, task_code=code, task_name=name, task_type=wt,
                priority="normal", status=se, progress=pct,
                plan_start_time=ps, plan_end_time=pe,
                actual_start_time=ast, actual_end_time=aet,
                duration_seconds=dur if se == "completed" else None, expected_duration=dur,
                owner= r.choice(SUR) + r.choice(GIV),
                max_retries=3, is_critical=("D1" in code or "D2" in code),
                notify_on_failure=True, created_at=now, updated_at=now
            ))
            total += 1
        session.commit()
        print(f"  Cycle {cid} ({am}): done")
    session.close()
    print(f"Total: {total} tasks across {len(CYCLES)} cycles")

if __name__ == "__main__":
    seed_billing_tasks()